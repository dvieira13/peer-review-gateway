import { randomUUID } from 'node:crypto';
import { badRequest } from '../errors';
import { REVIEWER_ROLES, type ReviewerRole, type RubricScope, type RubricSection } from './types';

const MAX_TEXT = 5000;
const MAX_NAME = 200;
const MAX_SECTIONS = 50;
const MAX_CRITERIA_PER_SECTION = 100;

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
export const isUuid = (v: string): boolean => UUID_RE.test(v);

const isObject = (v: unknown): v is Record<string, unknown> =>
  typeof v === 'object' && v !== null && !Array.isArray(v);

const isFiniteNumber = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v);

function optionalText(v: unknown, field: string, errors: string[], max = MAX_TEXT): string | null {
  if (v === undefined || v === null) return null;
  if (typeof v !== 'string') {
    errors.push(`${field} must be a string`);
    return null;
  }
  if (v.length > max) errors.push(`${field} must be at most ${max} characters`);
  return v;
}

function requiredText(v: unknown, field: string, errors: string[], max = MAX_TEXT): string {
  if (typeof v !== 'string' || v.trim() === '') {
    errors.push(`${field} is required and must be a non-empty string`);
    return '';
  }
  if (v.length > max) errors.push(`${field} must be at most ${max} characters`);
  return v.trim();
}

export interface RubricInput {
  name: string;
  description: string | null;
  scope: RubricScope;
  sections: RubricSection[];
}

/** Validates a POST/PUT rubric body. Criterion ids are generated by the server. */
export function parseRubricInput(body: unknown): RubricInput {
  if (!isObject(body)) throw badRequest('Request body must be a JSON object');
  const errors: string[] = [];

  const name = requiredText(body.name, 'name', errors, MAX_NAME);
  const description = optionalText(body.description, 'description', errors);

  const scopeFields = (['project_id', 'course_id', 'lab_id'] as const).filter(
    (f) => body[f] !== undefined && body[f] !== null,
  );
  let scope: RubricScope = { type: 'project', id: '' };
  if (scopeFields.length !== 1) {
    errors.push('exactly one of project_id, course_id or lab_id is required');
  } else {
    const field = scopeFields[0];
    const id = requiredText(body[field], field, errors, MAX_NAME);
    scope = { type: field === 'project_id' ? 'project' : field === 'course_id' ? 'course' : 'lab', id };
  }

  const sections: RubricSection[] = [];
  if (!Array.isArray(body.sections) || body.sections.length === 0) {
    errors.push('sections must be a non-empty array');
  } else if (body.sections.length > MAX_SECTIONS) {
    errors.push(`sections must contain at most ${MAX_SECTIONS} entries`);
  } else {
    body.sections.forEach((raw: unknown, si: number) => {
      const p = `sections[${si}]`;
      if (!isObject(raw)) {
        errors.push(`${p} must be an object`);
        return;
      }
      const title = requiredText(raw.title, `${p}.title`, errors, MAX_NAME);
      const sDesc = optionalText(raw.description, `${p}.description`, errors);
      const criteria: RubricSection['criteria'] = [];
      if (!Array.isArray(raw.criteria) || raw.criteria.length === 0) {
        errors.push(`${p}.criteria must be a non-empty array`);
      } else if (raw.criteria.length > MAX_CRITERIA_PER_SECTION) {
        errors.push(`${p}.criteria must contain at most ${MAX_CRITERIA_PER_SECTION} entries`);
      } else {
        raw.criteria.forEach((c: unknown, ci: number) => {
          const cp = `${p}.criteria[${ci}]`;
          if (!isObject(c)) {
            errors.push(`${cp} must be an object`);
            return;
          }
          const cDesc = requiredText(c.description, `${cp}.description`, errors);
          if (!isFiniteNumber(c.weight) || c.weight <= 0) errors.push(`${cp}.weight must be a number greater than 0`);
          if (!isFiniteNumber(c.max_points) || c.max_points <= 0)
            errors.push(`${cp}.max_points must be a number greater than 0`);
          criteria.push({
            id: randomUUID(),
            description: cDesc,
            weight: c.weight as number,
            max_points: c.max_points as number,
          });
        });
      }
      sections.push({ title, description: sDesc, criteria });
    });
  }

  if (errors.length > 0) throw badRequest('Invalid rubric', errors);
  return { name, description, scope, sections };
}

export interface ScoreInput {
  criterion_id: string;
  points: number;
  feedback: string | null;
}

function parseScores(v: unknown, errors: string[]): ScoreInput[] {
  const scores: ScoreInput[] = [];
  if (!Array.isArray(v) || v.length === 0) {
    errors.push('scores must be a non-empty array');
    return scores;
  }
  v.forEach((raw: unknown, i: number) => {
    const p = `scores[${i}]`;
    if (!isObject(raw)) {
      errors.push(`${p} must be an object`);
      return;
    }
    const criterion_id = requiredText(raw.criterion_id, `${p}.criterion_id`, errors, MAX_NAME);
    if (!isFiniteNumber(raw.points) || raw.points < 0) errors.push(`${p}.points must be a number >= 0`);
    const feedback = optionalText(raw.feedback, `${p}.feedback`, errors);
    scores.push({ criterion_id, points: raw.points as number, feedback });
  });
  return scores;
}

export interface ReviewInput {
  reviewer_id: string;
  reviewer_role: ReviewerRole;
  rubric_id: string;
  scores: ScoreInput[];
  comments: string | null;
}

/** Validates a POST review body (decision 5: reviewer_id and reviewer_role are in the body). */
export function parseReviewInput(body: unknown): ReviewInput {
  if (!isObject(body)) throw badRequest('Request body must be a JSON object');
  const errors: string[] = [];
  const reviewer_id = requiredText(body.reviewer_id, 'reviewer_id', errors, MAX_NAME);
  const role = body.reviewer_role;
  if (typeof role !== 'string' || !(REVIEWER_ROLES as readonly string[]).includes(role)) {
    errors.push(`reviewer_role must be one of ${REVIEWER_ROLES.join(', ')}`);
  }
  const rubric_id = requiredText(body.rubric_id, 'rubric_id', errors, MAX_NAME);
  const scores = parseScores(body.scores, errors);
  const comments = optionalText(body.comments, 'comments', errors);
  if (errors.length > 0) throw badRequest('Invalid review', errors);
  return { reviewer_id, reviewer_role: role as ReviewerRole, rubric_id, scores, comments };
}

export interface ReviewUpdateInput {
  scores: ScoreInput[];
  comments: string | null;
}

/**
 * Validates a PUT review body. Only scores and comments can change; the reviewer,
 * role and rubric of an existing review are fixed and are rejected if they differ.
 */
export function parseReviewUpdate(
  body: unknown,
  current: { reviewer_id: string; reviewer_role: string; rubric_id: string },
): ReviewUpdateInput {
  if (!isObject(body)) throw badRequest('Request body must be a JSON object');
  const errors: string[] = [];
  for (const f of ['reviewer_id', 'reviewer_role', 'rubric_id'] as const) {
    if (body[f] !== undefined && body[f] !== current[f]) errors.push(`${f} cannot be changed`);
  }
  const scores = parseScores(body.scores, errors);
  const comments = optionalText(body.comments, 'comments', errors);
  if (errors.length > 0) throw badRequest('Invalid review update', errors);
  return { scores, comments };
}

/** Express 5 query values can be string | string[] | undefined; accept a single string only. */
export function queryString(q: Record<string, unknown>, name: string): string | undefined {
  const v = q[name];
  if (v === undefined) return undefined;
  if (typeof v !== 'string') throw badRequest(`Query parameter ${name} must be given once`);
  return v;
}

export function queryMinScore(q: Record<string, unknown>, name = 'min_score'): number | undefined {
  const v = queryString(q, name);
  if (v === undefined) return undefined;
  const n = Number(v);
  if (v.trim() === '' || !Number.isFinite(n) || n < 0 || n > 100) {
    throw badRequest(`${name} must be a number between 0 and 100`);
  }
  return n;
}

export function queryEnum<T extends string>(
  q: Record<string, unknown>,
  name: string,
  allowed: readonly T[],
): T | undefined {
  const v = queryString(q, name);
  if (v === undefined) return undefined;
  if (!(allowed as readonly string[]).includes(v)) {
    throw badRequest(`${name} must be one of ${allowed.join(', ')}`);
  }
  return v as T;
}
